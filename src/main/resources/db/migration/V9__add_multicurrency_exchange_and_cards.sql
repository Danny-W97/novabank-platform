CREATE TABLE exchange_transactions (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id       BIGINT NOT NULL,
    source_currency  VARCHAR(3) NOT NULL,
    target_currency  VARCHAR(3) NOT NULL,
    source_amount    NUMERIC(19, 2) NOT NULL,
    target_amount    NUMERIC(19, 2) NOT NULL,
    applied_rate     NUMERIC(19, 8) NOT NULL,
    idempotency_key  VARCHAR(64) NOT NULL UNIQUE,
    status           VARCHAR(20) NOT NULL,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_exchange_transactions_account
        FOREIGN KEY (account_id) REFERENCES accounts (id) ON DELETE CASCADE,
    CONSTRAINT ck_exchange_transactions_currencies
        CHECK (source_currency IN ('PLN', 'EUR', 'USD', 'GBP', 'CHF')
            AND target_currency IN ('PLN', 'EUR', 'USD', 'GBP', 'CHF')
            AND source_currency <> target_currency),
    CONSTRAINT ck_exchange_transactions_amounts
        CHECK (source_amount > 0 AND target_amount > 0),
    CONSTRAINT ck_exchange_transactions_status
        CHECK (status IN ('COMPLETED', 'FAILED'))
);

CREATE INDEX ix_exchange_transactions_account_created
    ON exchange_transactions (account_id, created_at DESC);

CREATE TABLE demo_cards (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id      BIGINT NOT NULL UNIQUE,
    masked_number   VARCHAR(32) NOT NULL UNIQUE,
    status          VARCHAR(20) NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_demo_cards_account
        FOREIGN KEY (account_id) REFERENCES accounts (id) ON DELETE CASCADE,
    CONSTRAINT ck_demo_cards_status
        CHECK (status IN ('ACTIVE', 'BLOCKED'))
);

CREATE TABLE card_transactions (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    card_id          BIGINT NOT NULL,
    merchant_name    VARCHAR(120) NOT NULL,
    currency         VARCHAR(3) NOT NULL,
    amount           NUMERIC(19, 2) NOT NULL,
    idempotency_key  VARCHAR(64) NOT NULL UNIQUE,
    status           VARCHAR(20) NOT NULL,
    reason           VARCHAR(300),
    created_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_card_transactions_card
        FOREIGN KEY (card_id) REFERENCES demo_cards (id) ON DELETE CASCADE,
    CONSTRAINT ck_card_transactions_currency
        CHECK (currency IN ('PLN', 'EUR', 'USD', 'GBP', 'CHF')),
    CONSTRAINT ck_card_transactions_amount
        CHECK (amount > 0),
    CONSTRAINT ck_card_transactions_status
        CHECK (status IN ('COMPLETED', 'DECLINED'))
);

CREATE INDEX ix_card_transactions_card_created
    ON card_transactions (card_id, created_at DESC);
