CREATE TABLE currency_balances (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id  BIGINT NOT NULL,
    currency    VARCHAR(3) NOT NULL,
    balance     NUMERIC(19, 2) NOT NULL DEFAULT 0,
    version     BIGINT NOT NULL DEFAULT 0,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_currency_balances_account
        FOREIGN KEY (account_id) REFERENCES accounts (id) ON DELETE CASCADE,
    CONSTRAINT uk_currency_balances_account_currency
        UNIQUE (account_id, currency),
    CONSTRAINT ck_currency_balances_currency
        CHECK (currency IN ('PLN', 'EUR', 'USD', 'GBP', 'CHF')),
    CONSTRAINT ck_currency_balances_balance
        CHECK (balance >= 0)
);

CREATE INDEX ix_currency_balances_account
    ON currency_balances (account_id);

CREATE TABLE exchange_rates (
    currency    VARCHAR(3) PRIMARY KEY,
    rate_to_pln NUMERIC(19, 6) NOT NULL,
    active      BOOLEAN NOT NULL DEFAULT TRUE,
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT ck_exchange_rates_currency
        CHECK (currency IN ('PLN', 'EUR', 'USD', 'GBP', 'CHF')),
    CONSTRAINT ck_exchange_rates_rate
        CHECK (rate_to_pln > 0)
);

