ALTER TABLE users
    ADD COLUMN transaction_pin_hash VARCHAR(100);

CREATE TABLE saved_recipients (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id        BIGINT NOT NULL,
    alias           VARCHAR(100) NOT NULL,
    recipient_name  VARCHAR(201) NOT NULL,
    account_number  CHAR(26) NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL,
    updated_at      TIMESTAMPTZ NOT NULL,

    CONSTRAINT fk_saved_recipients_owner
        FOREIGN KEY (owner_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT uk_saved_recipients_owner_account
        UNIQUE (owner_id, account_number),
    CONSTRAINT ck_saved_recipients_account_number
        CHECK (account_number ~ '^[0-9]{26}$')
);

CREATE INDEX ix_saved_recipients_owner_alias
    ON saved_recipients (owner_id, alias);

CREATE TABLE notifications (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL,
    type        VARCHAR(20) NOT NULL,
    message     VARCHAR(300) NOT NULL,
    is_read     BOOLEAN NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMPTZ NOT NULL,

    CONSTRAINT fk_notifications_user
        FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_notifications_type
        CHECK (type IN ('INFO', 'SUCCESS', 'SECURITY'))
);

CREATE INDEX ix_notifications_user_created
    ON notifications (user_id, created_at DESC);

CREATE TABLE operation_audits (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_email  VARCHAR(254),
    operation   VARCHAR(40) NOT NULL,
    reason      VARCHAR(300) NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL
);

CREATE INDEX ix_operation_audits_created
    ON operation_audits (created_at DESC);

CREATE INDEX ix_operation_audits_user_created
    ON operation_audits (user_email, created_at DESC);
