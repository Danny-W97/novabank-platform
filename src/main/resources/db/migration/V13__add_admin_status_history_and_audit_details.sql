ALTER TABLE operation_audits
    ADD COLUMN IF NOT EXISTS target_user_email VARCHAR(254),
    ADD COLUMN IF NOT EXISTS target_account_id BIGINT,
    ADD COLUMN IF NOT EXISTS ip_address VARCHAR(64),
    ADD COLUMN IF NOT EXISTS success BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN IF NOT EXISTS admin_action BOOLEAN NOT NULL DEFAULT FALSE;

CREATE INDEX IF NOT EXISTS ix_operation_audits_admin_created
    ON operation_audits (admin_action, created_at DESC);

CREATE TABLE admin_status_changes (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id               BIGINT,
    account_number           CHAR(26) NOT NULL,
    user_email               VARCHAR(254) NOT NULL,
    previous_account_status  VARCHAR(20),
    new_account_status       VARCHAR(20) NOT NULL,
    previous_user_status     VARCHAR(20),
    new_user_status          VARCHAR(20) NOT NULL,
    changed_by               VARCHAR(254) NOT NULL,
    reason                   VARCHAR(300) NOT NULL,
    ip_address               VARCHAR(64),
    created_at               TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_admin_status_changes_account
        FOREIGN KEY (account_id) REFERENCES accounts (id) ON DELETE SET NULL,
    CONSTRAINT ck_admin_status_changes_account_number
        CHECK (account_number ~ '^[0-9]{26}$')
);

CREATE INDEX ix_admin_status_changes_created
    ON admin_status_changes (created_at DESC);

CREATE INDEX ix_admin_status_changes_user_created
    ON admin_status_changes (user_email, created_at DESC);
