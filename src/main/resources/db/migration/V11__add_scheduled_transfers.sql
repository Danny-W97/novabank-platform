CREATE TABLE scheduled_transfers (
    id                           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                      BIGINT NOT NULL,
    destination_account_number   VARCHAR(26) NOT NULL,
    recipient_name               VARCHAR(201) NOT NULL,
    amount                       NUMERIC(19,2) NOT NULL,
    title                        VARCHAR(140) NOT NULL,
    frequency                    VARCHAR(12) NOT NULL,
    next_execution_at            TIMESTAMPTZ NOT NULL,
    active                       BOOLEAN NOT NULL DEFAULT TRUE,
    last_executed_at             TIMESTAMPTZ,
    last_error                   VARCHAR(300),
    created_at                   TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_scheduled_transfers_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT ck_scheduled_transfers_frequency CHECK (frequency IN ('ONCE', 'DAILY', 'WEEKLY', 'MONTHLY')),
    CONSTRAINT ck_scheduled_transfers_amount CHECK (amount > 0)
);

CREATE INDEX ix_scheduled_transfers_due ON scheduled_transfers (active, next_execution_at);
CREATE INDEX ix_scheduled_transfers_user ON scheduled_transfers (user_id, next_execution_at);
