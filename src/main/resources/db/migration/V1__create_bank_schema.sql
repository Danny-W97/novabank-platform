CREATE TABLE users (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email           VARCHAR(254) NOT NULL,
    password_hash   VARCHAR(100) NOT NULL,
    first_name      VARCHAR(100) NOT NULL,
    last_name       VARCHAR(100) NOT NULL,
    phone           VARCHAR(32),
    birth_date      DATE,
    role            VARCHAR(20) NOT NULL,
    status          VARCHAR(20) NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL,
    updated_at      TIMESTAMPTZ NOT NULL,
    last_login_at   TIMESTAMPTZ,

    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT ck_users_email_normalized CHECK (email = LOWER(BTRIM(email))),
    CONSTRAINT ck_users_role CHECK (role IN ('USER', 'ADMIN')),
    CONSTRAINT ck_users_status CHECK (status IN ('ACTIVE', 'BLOCKED'))
);

CREATE TABLE accounts (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_number  CHAR(26) NOT NULL,
    owner_id        BIGINT NOT NULL,
    balance         NUMERIC(19, 2) NOT NULL,
    currency        CHAR(3) NOT NULL,
    status          VARCHAR(20) NOT NULL,
    version         BIGINT NOT NULL DEFAULT 0,
    created_at      TIMESTAMPTZ NOT NULL,
    updated_at      TIMESTAMPTZ NOT NULL,

    CONSTRAINT uk_accounts_account_number UNIQUE (account_number),
    CONSTRAINT uk_accounts_owner UNIQUE (owner_id),
    CONSTRAINT fk_accounts_owner FOREIGN KEY (owner_id) REFERENCES users (id),
    CONSTRAINT ck_accounts_number CHECK (account_number ~ '^[0-9]{26}$'),
    CONSTRAINT ck_accounts_balance CHECK (balance >= 0),
    CONSTRAINT ck_accounts_currency CHECK (currency ~ '^[A-Z]{3}$'),
    CONSTRAINT ck_accounts_status CHECK (status IN ('ACTIVE', 'BLOCKED', 'CLOSED'))
);

CREATE TABLE bank_transactions (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference_number         VARCHAR(32) NOT NULL,
    idempotency_key          VARCHAR(64) NOT NULL,
    source_account_id        BIGINT,
    destination_account_id   BIGINT NOT NULL,
    sender_name_snapshot     VARCHAR(201),
    recipient_name_snapshot  VARCHAR(201) NOT NULL,
    amount                   NUMERIC(19, 2) NOT NULL,
    currency                 CHAR(3) NOT NULL,
    title                    VARCHAR(140) NOT NULL,
    type                     VARCHAR(24) NOT NULL,
    status                   VARCHAR(20) NOT NULL,
    created_at               TIMESTAMPTZ NOT NULL,
    completed_at             TIMESTAMPTZ,

    CONSTRAINT uk_transactions_reference UNIQUE (reference_number),
    CONSTRAINT uk_transactions_idempotency UNIQUE (idempotency_key),
    CONSTRAINT fk_transactions_source FOREIGN KEY (source_account_id) REFERENCES accounts (id),
    CONSTRAINT fk_transactions_destination FOREIGN KEY (destination_account_id) REFERENCES accounts (id),
    CONSTRAINT ck_transactions_amount CHECK (amount > 0),
    CONSTRAINT ck_transactions_currency CHECK (currency ~ '^[A-Z]{3}$'),
    CONSTRAINT ck_transactions_type CHECK (type IN ('INITIAL_CREDIT', 'TRANSFER', 'PAYMENT')),
    CONSTRAINT ck_transactions_status CHECK (status IN ('PENDING', 'COMPLETED', 'FAILED')),
    CONSTRAINT ck_transactions_accounts CHECK (
        (type = 'INITIAL_CREDIT' AND source_account_id IS NULL)
        OR
        (type <> 'INITIAL_CREDIT' AND source_account_id IS NOT NULL)
    )
);

CREATE INDEX ix_transactions_source_created
    ON bank_transactions (source_account_id, created_at DESC);

CREATE INDEX ix_transactions_destination_created
    ON bank_transactions (destination_account_id, created_at DESC);
