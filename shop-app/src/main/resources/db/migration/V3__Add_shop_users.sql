CREATE TABLE shop_users (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email                VARCHAR(254) NOT NULL,
    password_hash        VARCHAR(100) NOT NULL,
    customer_id          VARCHAR(100) NOT NULL,
    bank_account_number  CHAR(26) NOT NULL,
    active               BOOLEAN NOT NULL DEFAULT TRUE,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at           TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_shop_users_email UNIQUE (email),
    CONSTRAINT uk_shop_users_customer_id UNIQUE (customer_id),
    CONSTRAINT ck_shop_users_email_normalized CHECK (email = LOWER(BTRIM(email))),
    CONSTRAINT ck_shop_users_customer_id CHECK (customer_id = BTRIM(customer_id)),
    CONSTRAINT ck_shop_users_account_number CHECK (bank_account_number ~ '^[0-9]{26}$')
);

CREATE INDEX ix_shop_users_active_email
    ON shop_users (email)
    WHERE active = TRUE;
