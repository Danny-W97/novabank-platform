CREATE TABLE shop_refunds (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id         BIGINT NOT NULL REFERENCES shop_orders(id),
    order_number     VARCHAR(36) NOT NULL,
    idempotency_key  VARCHAR(64) NOT NULL UNIQUE,
    amount           NUMERIC(19,2) NOT NULL,
    currency         CHAR(3) NOT NULL,
    status           VARCHAR(16) NOT NULL,
    reason           VARCHAR(140) NOT NULL,
    bank_reference   VARCHAR(32),
    failure_reason   VARCHAR(500),
    created_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_shop_refunds_amount CHECK (amount > 0),
    CONSTRAINT ck_shop_refunds_status CHECK (status IN ('PENDING', 'COMPLETED', 'FAILED'))
);

CREATE INDEX ix_shop_refunds_order ON shop_refunds (order_id, created_at DESC);

-- Allows at most one active or completed refund per order.
-- A FAILED refund may be retried with a new Idempotency-Key.
CREATE UNIQUE INDEX uk_shop_refunds_one_active_per_order
    ON shop_refunds (order_id)
    WHERE status IN ('PENDING', 'COMPLETED');
