CREATE TABLE IF NOT EXISTS shop_products (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku             VARCHAR(64) NOT NULL UNIQUE,
    name            VARCHAR(200) NOT NULL,
    description     VARCHAR(1000),
    price           NUMERIC(19, 2) NOT NULL,
    currency        CHAR(3) NOT NULL,
    active          BOOLEAN NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_shop_products_price     CHECK (price > 0),
    CONSTRAINT ck_shop_products_currency  CHECK (currency ~ '^[A-Z]{3}$')
);

CREATE TABLE IF NOT EXISTS shop_carts (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id     VARCHAR(100) NOT NULL UNIQUE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS shop_cart_items (
    cart_id         BIGINT NOT NULL REFERENCES shop_carts(id) ON DELETE CASCADE,
    product_id      BIGINT NOT NULL REFERENCES shop_products(id),
    quantity        INTEGER NOT NULL,
    PRIMARY KEY (cart_id, product_id),
    CONSTRAINT ck_shop_cart_items_quantity CHECK (quantity > 0 AND quantity <= 99)
);

CREATE TABLE IF NOT EXISTS shop_orders (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number             VARCHAR(36) NOT NULL UNIQUE,
    customer_id              VARCHAR(100) NOT NULL,
    customer_account_number  CHAR(26) NOT NULL,
    merchant_account_number  CHAR(26) NOT NULL,
    total                    NUMERIC(19, 2) NOT NULL,
    currency                 CHAR(3) NOT NULL,
    status                   VARCHAR(16) NOT NULL,
    payment_idempotency_key  VARCHAR(64),
    bank_reference           VARCHAR(32),
    failure_reason           VARCHAR(500),
    created_at               TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at               TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_shop_orders_total CHECK (total > 0),
    CONSTRAINT ck_shop_orders_status CHECK (status IN ('PENDING', 'PAID', 'FAILED')),
    CONSTRAINT uk_shop_orders_payment_key UNIQUE (payment_idempotency_key)
);

CREATE TABLE IF NOT EXISTS shop_order_items (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id        BIGINT NOT NULL REFERENCES shop_orders(id) ON DELETE CASCADE,
    product_id      BIGINT NOT NULL,
    sku             VARCHAR(64) NOT NULL,
    product_name    VARCHAR(200) NOT NULL,
    unit_price      NUMERIC(19, 2) NOT NULL,
    quantity        INTEGER NOT NULL,
    line_total      NUMERIC(19, 2) NOT NULL,
    CONSTRAINT ck_shop_order_items_quantity CHECK (quantity > 0),
    CONSTRAINT ck_shop_order_items_price CHECK (unit_price > 0 AND line_total > 0)
);

CREATE INDEX IF NOT EXISTS ix_shop_orders_customer_created
    ON shop_orders (customer_id, created_at DESC);

